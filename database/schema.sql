CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(8) NOT NULL UNIQUE,
    title varchar(100) NOT NULL,
    hours integer NOT NULL CHECK (hours > 0)
);
CREATE TABLE instructors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    phone varchar(24) NOT NULL,
    certificate varchar(32) NOT NULL UNIQUE
);
CREATE TABLE cars (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model varchar(100) NOT NULL,
    plate varchar(18) NOT NULL UNIQUE,
    transmission varchar(6) NOT NULL CHECK (transmission IN ('MANUAL', 'AUTO')),
    category_id bigint NOT NULL REFERENCES categories
);
CREATE TABLE study_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(40) NOT NULL UNIQUE CHECK (btrim(title) <> ''),
    category_id bigint NOT NULL REFERENCES categories,
    instructor_id bigint NOT NULL REFERENCES instructors,
    start_date date NOT NULL,
    end_date date NOT NULL CHECK (end_date >= start_date),
    capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 40),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE TABLE students (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL CHECK (length(btrim(name)) >= 3),
    phone varchar(24) NOT NULL UNIQUE CHECK (phone ~ '^[+][0-9]{10,15}$'),
    group_id bigint NOT NULL REFERENCES study_groups,
    status varchar(12) NOT NULL CHECK (status IN ('STUDYING', 'PAUSED', 'GRADUATED')),
    enrolled_on date NOT NULL,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE TABLE lessons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES students,
    instructor_id bigint NOT NULL REFERENCES instructors,
    car_id bigint NOT NULL REFERENCES cars,
    starts_at timestamp(0) NOT NULL,
    duration_minutes integer NOT NULL CHECK (duration_minutes BETWEEN 30 AND 180),
    status varchar(10) NOT NULL CHECK (status IN ('PLANNED', 'DONE', 'CANCELED')),
    note varchar(300) NOT NULL DEFAULT '',
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    -- [) разрешает поставить следующее занятие ровно на время окончания предыдущего.
    slot tsrange GENERATED ALWAYS AS
        (tsrange(starts_at, starts_at + duration_minutes * interval '1 minute', '[)')) STORED,
    CONSTRAINT lesson_student_slot EXCLUDE USING gist (student_id WITH =, slot WITH &&) WHERE (status <> 'CANCELED'),
    CONSTRAINT lesson_instructor_slot EXCLUDE USING gist (instructor_id WITH =, slot WITH &&) WHERE (status <> 'CANCELED'),
    CONSTRAINT lesson_car_slot EXCLUDE USING gist (car_id WITH =, slot WITH &&) WHERE (status <> 'CANCELED')
);
CREATE INDEX cars_category_idx ON cars(category_id);
CREATE INDEX groups_category_idx ON study_groups(category_id);
CREATE INDEX groups_instructor_idx ON study_groups(instructor_id);
CREATE INDEX students_group_idx ON students(group_id);
CREATE INDEX lessons_student_idx ON lessons(student_id);
CREATE INDEX lessons_instructor_idx ON lessons(instructor_id);
CREATE INDEX lessons_car_idx ON lessons(car_id);
CREATE INDEX lessons_time_idx ON lessons(starts_at);

CREATE FUNCTION check_group_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.category_id <> OLD.category_id THEN
        RAISE EXCEPTION USING ERRCODE = 'P2001', MESSAGE = 'Категорию существующей группы изменить нельзя.';
    END IF;
    IF NEW.capacity < OLD.capacity AND
        (SELECT count(*) FROM students WHERE group_id = OLD.id) > NEW.capacity THEN
        RAISE EXCEPTION USING ERRCODE = 'P2001', MESSAGE = 'В группе уже больше учеников, чем указано мест.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER check_group_before_update
    BEFORE UPDATE ON study_groups FOR EACH ROW EXECUTE FUNCTION check_group_update();

CREATE FUNCTION check_student_group() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE allowed integer;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.group_id = OLD.group_id THEN RETURN NEW; END IF;
    IF TG_OP = 'UPDATE' AND EXISTS (SELECT 1 FROM lessons WHERE student_id = OLD.id) THEN
        RAISE EXCEPTION USING ERRCODE = 'P2001', MESSAGE = 'Ученик с занятиями не может быть переведён в другую группу.';
    END IF;
    -- Запись в одну группу сериализуется блокировкой строки этой группы.
    SELECT capacity INTO allowed FROM study_groups WHERE id = NEW.group_id FOR UPDATE;
    IF allowed IS NOT NULL AND (SELECT count(*) FROM students WHERE group_id = NEW.group_id) >= allowed THEN
        RAISE EXCEPTION USING ERRCODE = 'P2001', MESSAGE = 'В выбранной группе нет свободных мест.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER check_student_before_write
    BEFORE INSERT OR UPDATE OF group_id ON students FOR EACH ROW EXECUTE FUNCTION check_student_group();

CREATE FUNCTION check_lesson_write() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE group_category bigint;
DECLARE car_category bigint;
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.status <> 'PLANNED' THEN
        RAISE EXCEPTION USING ERRCODE = 'P2001', MESSAGE = 'Проведённое или отменённое занятие уже нельзя изменить.';
    END IF;
    SELECT g.category_id INTO group_category FROM students s
        JOIN study_groups g ON g.id = s.group_id WHERE s.id = NEW.student_id FOR UPDATE OF s;
    SELECT category_id INTO car_category FROM cars WHERE id = NEW.car_id;
    IF group_category <> car_category THEN
        RAISE EXCEPTION USING ERRCODE = 'P2001', MESSAGE = 'Категория автомобиля не совпадает с категорией группы ученика.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER check_lesson_before_write
    BEFORE INSERT OR UPDATE ON lessons FOR EACH ROW EXECUTE FUNCTION check_lesson_write();

-- NULL в p_id означает создание. Версия предохраняет от потери правок другого клиента.
CREATE PROCEDURE save_group(p_id bigint, p_version integer, p_title text, p_category bigint, p_instructor bigint,
                            p_start date, p_end date, p_capacity integer)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_id IS NULL THEN
        INSERT INTO study_groups(title, category_id, instructor_id, start_date, end_date, capacity)
        VALUES (btrim(p_title), p_category, p_instructor, p_start, p_end, p_capacity);
    ELSE
        UPDATE study_groups SET title = btrim(p_title), category_id = p_category, instructor_id = p_instructor,
            start_date = p_start, end_date = p_end, capacity = p_capacity, version = version + 1
        WHERE id = p_id AND version = p_version;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'P2002', MESSAGE = 'Группа уже изменилась. Обновите данные.'; END IF;
    END IF;
END $$;

CREATE PROCEDURE save_student(p_id bigint, p_version integer, p_name text, p_phone text, p_group bigint,
                              p_status text, p_enrolled date)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_id IS NULL THEN
        INSERT INTO students(name, phone, group_id, status, enrolled_on)
        VALUES (btrim(p_name), p_phone, p_group, p_status, p_enrolled);
    ELSE
        UPDATE students SET name = btrim(p_name), phone = p_phone, group_id = p_group, status = p_status,
            enrolled_on = p_enrolled, version = version + 1 WHERE id = p_id AND version = p_version;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'P2002', MESSAGE = 'Карточка ученика уже изменилась. Обновите данные.'; END IF;
    END IF;
END $$;

CREATE PROCEDURE save_lesson(p_id bigint, p_version integer, p_student bigint, p_instructor bigint, p_car bigint,
                             p_start timestamp, p_minutes integer, p_status text, p_note text)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_id IS NULL THEN
        IF p_status <> 'PLANNED' THEN
            RAISE EXCEPTION USING ERRCODE = 'P2001', MESSAGE = 'Новое занятие должно быть запланировано.';
        END IF;
        INSERT INTO lessons(student_id, instructor_id, car_id, starts_at, duration_minutes, status, note)
        VALUES (p_student, p_instructor, p_car, p_start, p_minutes, p_status, p_note);
    ELSE
        UPDATE lessons SET student_id = p_student, instructor_id = p_instructor, car_id = p_car, starts_at = p_start,
            duration_minutes = p_minutes, status = p_status, note = p_note, version = version + 1
        WHERE id = p_id AND version = p_version;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'P2002', MESSAGE = 'Занятие уже изменилось. Обновите данные.'; END IF;
    END IF;
END $$;
